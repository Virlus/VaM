"""Restart-safe, byte-preserving registration of completed LeRobot uploads."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from preprocess_data.utils.episode_io import _copy_remapped_episode
from preprocess_data.utils.episode_io import _load_json
from preprocess_data.utils.episode_io import _read_jsonl
from preprocess_data.utils.episode_io import _read_tasks
from preprocess_data.utils.episode_io import _remap_episode_stats
from preprocess_data.utils.episode_io import _write_json
from preprocess_data.utils.episode_io import _write_jsonl


def append_uploaded_episodes(
    source_root: Path, target_root: Path, *, source_id: str, policy: dict[str, Any]
) -> list[int]:
    """Append a completed v2.1 upload without decoding video; caller holds the registrar lock.

    append_state commits after episode files and before metadata. A retry repairs metadata
    from that record; no committed episode file is overwritten. Readers must
    use published episode_ids, never glob an actively growing repo.
    """
    info = _load_json(source_root / "meta/info.json")
    for key, expected in {
        "codebase_version": "v2.1",
        "data_path": "data/chunk-{episode_chunk:03d}/episode_{episode_index:06d}.parquet",
        "video_path": "videos/chunk-{episode_chunk:03d}/{video_key}/episode_{episode_index:06d}.mp4",
    }.items():
        if info.get(key) != expected:
            raise ValueError(f"Unsupported upload {key}: {info.get(key)}")
    target_root.mkdir(parents=True, exist_ok=True)
    meta = target_root / "meta"
    meta.mkdir(exist_ok=True)
    state_path = meta / "append_state.json"
    if state_path.exists():
        state = _load_json(state_path)
    else:
        if (meta / "info.json").exists():
            raise ValueError(f"Refusing append into unmanaged repo {target_root}")
        empty_info = json.loads(json.dumps(info))
        empty_info.update(total_episodes=0, total_frames=0, total_videos=0, total_chunks=0, total_tasks=0)
        state = {
            "info": empty_info,
            "episodes": [],
            "episodes_stats": [],
            "tasks": [],
            "policy_metadata_map": [],
            "uploads": {},
        }
        _write_json(state_path, state)
    if source_id in state["uploads"]:
        # Metadata might have been interrupted after the commit record was written.
        _publish_append_metadata(meta, state)
        return state["uploads"][source_id]
    for key in ("fps", "robot_type", "codebase_version", "data_path", "video_path"):
        if info.get(key) != state["info"].get(key):
            raise ValueError(f"Upload {source_id} differs in {key}")

    # advantage is generated by the registrar, so recorder uploads may omit it.
    def features(value):
        return {k: v for k, v in value["features"].items() if k != "advantage"}

    if features(info) != features(state["info"]):
        raise ValueError(f"Upload {source_id} differs in features")
    episodes = _read_jsonl(source_root / "meta/episodes.jsonl")
    stats = _read_jsonl(source_root / "meta/episodes_stats.jsonl")
    if [e["episode_index"] for e in episodes] != list(range(info["total_episodes"])):
        raise ValueError("Upload episodes must be contiguous")
    task_indices = {row["task"]: row["task_index"] for row in state["tasks"]}
    task_map = {}
    for row in _read_tasks(source_root / "meta/tasks.jsonl"):
        if row["task"] not in task_indices:
            task_indices[row["task"]] = len(state["tasks"])
            state["tasks"].append({"task_index": task_indices[row["task"]], "task": row["task"]})
        task_map[row["task_index"]] = task_indices[row["task"]]
    mapping_path = source_root / "meta/policy_metadata_map.jsonl"
    mapping = _read_jsonl(mapping_path) if mapping_path.exists() else [{} for _ in episodes]
    video_keys = [k for k, v in info["features"].items() if v["dtype"] == "video"]
    offset = state["info"]["total_frames"]
    ids = []
    for episode, stat, provenance in zip(episodes, stats, mapping, strict=True):
        index = len(state["episodes"])
        count = _copy_remapped_episode(
            source_root=source_root,
            target_root=target_root,
            source_episode_index=episode["episode_index"],
            target_episode_index=index,
            frame_offset=offset,
            source_chunks_size=info["chunks_size"],
            target_chunks_size=state["info"]["chunks_size"],
            task_index_map=task_map,
            video_keys=video_keys,
        )
        if count != episode["length"]:
            raise ValueError("Upload length differs from parquet")
        state["episodes"].append({**episode, "episode_index": index})
        _remap_episode_stats(stat, index, offset, task_map)
        state["episodes_stats"].append(stat)
        state["policy_metadata_map"].append(
            {
                **provenance,
                **policy,
                "target_episode_index": index,
                "source_episode_index": episode["episode_index"],
                "source_upload_id": source_id,
            }
        )
        state["info"]["total_frames"] += count
        ids.append(index)
    count = len(state["episodes"])
    state["info"].update(
        total_episodes=count,
        total_videos=count * len(video_keys),
        total_tasks=len(state["tasks"]),
        total_chunks=(count + state["info"]["chunks_size"] - 1) // state["info"]["chunks_size"],
        splits={"train": f"0:{count}"},
    )
    state["uploads"][source_id] = ids
    _write_json(state_path, state)
    _publish_append_metadata(meta, state)
    return ids


def _publish_append_metadata(meta: Path, state: dict[str, Any]) -> None:
    for name in ("tasks", "episodes_stats", "policy_metadata_map", "episodes"):
        _write_jsonl(meta / f"{name}.jsonl", state[name])
    _write_json(meta / "info.json", state["info"])
