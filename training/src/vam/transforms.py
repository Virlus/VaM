@runtime_checkable
class DataTransformFn(Protocol):
    def __call__(self, data: DataDict) -> DataDict:
        """Apply transformation to the data.

        Args:
            data: The data to apply the transform to. This is a possibly nested dictionary that contains
                unbatched data elements. Each leaf is expected to be a numpy array. Using JAX arrays is allowed
                but not recommended since it may result in extra GPU memory usage inside data loader worker
                processes.

        Returns:
            The transformed data. Could be the input `data` that was modified in place, or a new data structure.
        """


@dataclasses.dataclass(frozen=True)
class Group:
    """A group of transforms."""

    # Transforms that are applied to the model input data.
    inputs: Sequence[DataTransformFn] = ()

    # Transforms that are applied to the model output data.
    outputs: Sequence[DataTransformFn] = ()

    def push(self, *, inputs: Sequence[DataTransformFn] = (), outputs: Sequence[DataTransformFn] = ()) -> "Group":
        """Append transforms to the group and return a new group.

        Args:
            inputs: Appended to the *end* of the current input transforms.
            outputs: Appended to the *beginning* of the current output transforms.

        Returns:
            A new group with the appended transforms.
        """
        return Group(inputs=(*self.inputs, *inputs), outputs=(*outputs, *self.outputs))


@dataclasses.dataclass(frozen=True)
class CompositeTransform(DataTransformFn):
    """A composite transform that applies a sequence of transforms in order."""

    transforms: Sequence[DataTransformFn]

    def __call__(self, data: DataDict) -> DataDict:
        for transform in self.transforms:
            data = transform(data)
        return data


def compose(transforms: Sequence[DataTransformFn]) -> DataTransformFn:
    """Compose a sequence of transforms into a single transform."""
    return CompositeTransform(transforms)


@dataclasses.dataclass(frozen=True)
class RepackTransform(DataTransformFn):
    """Repacks an input dictionary into a new dictionary.

    Repacking is defined using a dictionary where the keys are the new keys and the values
    are the flattened paths to the old keys. We use '/' as the separator during flattening.

    Example:
    {
        "images": {
            "cam_high": "observation.images.top",
            "cam_low": "observation.images.bottom",
        },
        "state": "observation.state",
        "actions": "action",
    }

    Optional fields: Some fields may not exist in the dataset (e.g., during inference when
    certain data fields are generated by the model rather than read from the dataset).
    Use the `optional_keys` parameter to specify which fields can be missing. If a field
    is missing and listed in `optional_keys`, it will simply be excluded from the output.
    """

    structure: at.PyTree[str]
    optional_keys: set[str] = dataclasses.field(default_factory=set)

    def __call__(self, data: DataDict) -> DataDict:
        flat_item = flatten_dict(data)

        def safe_get(key):
            if key in self.optional_keys and key not in flat_item:
                return None
            return flat_item[key]

        return jax.tree.map(safe_get, self.structure)


@dataclasses.dataclass(frozen=True)
class LowDimNormInputs(DataTransformFn):
    """Keep only low-dimensional fields needed by normalization stats."""

    action_horizon: int
    use_next_obs: bool = False

    def _action_chunk(self, actions) -> np.ndarray:
        actions = np.asarray(actions, dtype=np.float32)
        if actions.ndim >= 3 and actions.shape[0] == 1:
            actions = actions[0]
        return actions[: self.action_horizon]

    def __call__(self, data: DataDict) -> DataDict:
        inputs = {
            "state": np.asarray(data["observation/state"], dtype=np.float32),
            "actions": self._action_chunk(data["actions"]),
        }
        if self.use_next_obs:
            inputs["next_state"] = np.asarray(data["observation/next_state"], dtype=np.float32)
            inputs["next_actions"] = self._action_chunk(data["next_actions"])
        return inputs


def _ensure_feature_dim(data: DataDict, key: str, axis: int) -> DataDict:
    """Ensure that a scalar feature under ``key`` has an explicit singleton dimension."""
    value = data.get(key)
    if value is None:
        return data

    array = np.asarray(value)
    if array.ndim == 0:
        array = np.expand_dims(array, axis=0)
    elif array.shape[-1] != 1:
        if axis < 0:
            axis = array.ndim + axis + 1
        array = np.expand_dims(array, axis=axis)

    data[key] = array
    return data


