@dataclasses.dataclass(frozen=True)
class DiscretizeValues(DataTransformFn):
    """Discretize values into n_bins using HL-Gauss label smoothing."""

    n_bins: int
    vmin: float
    vmax: float
    gaussian_sigma: float | None = None

    def __call__(self, data: DataDict) -> DataDict:
        if data.get("value") is None:
            return data
        value = np.asarray(data["value"], dtype=np.float32)
        if value.ndim == 0:
            raise ValueError("Value must be a 1D array")
        elif value.ndim == 1:
            batch_shape = ()
        else:
            batch_shape = value.shape[:-1]

        flat_values = value.reshape(-1)
        bin_centers = np.linspace(self.vmin, self.vmax, self.n_bins, dtype=np.float32)
        sigma = self.gaussian_sigma
        if sigma is None:
            if self.n_bins < 2:
                raise ValueError("n_bins must be at least 2 for Gaussian labels.")
            sigma = float(bin_centers[1] - bin_centers[0])
        sigma = max(sigma, np.finfo(np.float32).tiny)

        # HL-Gauss: convert scalar targets to a Gaussian-smoothed histogram label.
        diffs = flat_values[:, None] - bin_centers[None, :]
        unnormalized = np.exp(-0.5 * np.square(diffs / sigma))
        weights = unnormalized.astype(np.float32)
        row_sums = weights.sum(axis=1, keepdims=True)
        row_sums = np.where(row_sums == 0.0, 1.0, row_sums)
        distributions = weights / row_sums

        data["value"] = distributions.reshape(*batch_shape, self.n_bins)
        return data


@dataclasses.dataclass(frozen=True)
class SerializeValues(DataTransformFn):
    """Serialize discrete value predictions into a single scalar value."""

    n_bins: int
    vmin: float
    vmax: float

    def __call__(self, data: DataDict) -> DataDict:
        if data.get("value") is None:
            return data
        value = np.asarray(data["value"], dtype=np.float32)
        bins = np.linspace(self.vmin, self.vmax, self.n_bins, dtype=np.float32)
        serialized_value = np.sum(value * bins, axis=-1, keepdims=True)
        data["value"] = serialized_value
        return data


