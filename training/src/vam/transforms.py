@dataclasses.dataclass(frozen=True)
class TokenizePrompt(DataTransformFn):
    tokenizer: _tokenizer.PaligemmaTokenizer
    discrete_state_input: bool = False
    use_next_obs: bool = False
    disable_proprio_for_value: bool = False
    retain_original_prompt: bool = False
    omit_state_from_prompt: bool = False

    def __call__(self, data: DataDict) -> DataDict:
        if not self.retain_original_prompt:
            prompt = data.pop("prompt", None)
        else:
            prompt = data.get("prompt", None)

        if prompt is None:
            raise ValueError("Prompt is required")

        if self.discrete_state_input:
            if (state := data.get("state", None)) is None:
                raise ValueError("State is required.")
            state = current_observation_state(state)
            if self.use_next_obs:
                if (next_state := data.get("next_state", None)) is None:
                    raise ValueError("Next state is required.")
                next_state = current_observation_state(next_state)
        else:
            state = None
            next_state = None

        bsz = 1
        prompt_ndims = 0
        if not isinstance(prompt, str):
            try:
                prompt_ndims = len(prompt.shape)
                prompt = prompt.item()
            except Exception:
                bsz = prompt.shape[0]
                prompt = prompt[0]

        tokens, token_masks, value_tokens, value_token_masks = self.tokenizer.tokenize(
            prompt,
            state,
            disable_proprio_for_value=self.disable_proprio_for_value,
            omit_state_from_prompt=self.omit_state_from_prompt,
        )
        if bsz > 1 or prompt_ndims > 0:
            tokens = np.repeat(tokens[None, ...], bsz, axis=0)
            token_masks = np.repeat(token_masks[None, ...], bsz, axis=0)
            if self.disable_proprio_for_value:
                assert value_tokens is not None and value_token_masks is not None
                value_tokens = np.repeat(value_tokens[None, ...], bsz, axis=0)
                value_token_masks = np.repeat(value_token_masks[None, ...], bsz, axis=0)
            else:
                value_tokens = None
                value_token_masks = None
        if self.use_next_obs:
            next_tokens, next_token_masks, next_value_tokens, next_value_token_masks = self.tokenizer.tokenize(
                prompt,
                next_state,
                disable_proprio_for_value=self.disable_proprio_for_value,
                omit_state_from_prompt=self.omit_state_from_prompt,
            )
            if bsz > 1 or prompt_ndims > 0:
                next_tokens = np.repeat(next_tokens[None, ...], bsz, axis=0)
                next_token_masks = np.repeat(next_token_masks[None, ...], bsz, axis=0)
                if self.disable_proprio_for_value:
                    assert next_value_tokens is not None and next_value_token_masks is not None
                    next_value_tokens = np.repeat(next_value_tokens[None, ...], bsz, axis=0)
                    next_value_token_masks = np.repeat(next_value_token_masks[None, ...], bsz, axis=0)
                else:
                    next_value_tokens = None
                    next_value_token_masks = None
        tokenized_outputs = {
            **data,
            "tokenized_prompt": tokens,
            "tokenized_prompt_mask": token_masks,
            "tokenized_value_prompt": value_tokens,
            "tokenized_value_prompt_mask": value_token_masks,
        }
        if self.use_next_obs:
            tokenized_outputs.update(
                {
                    "next_tokenized_prompt": next_tokens,
                    "next_tokenized_prompt_mask": next_token_masks,
                    "next_tokenized_value_prompt": next_value_tokens,
                    "next_tokenized_value_prompt_mask": next_value_token_masks,
                }
            )

        return tokenized_outputs


