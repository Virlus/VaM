"""Async streaming control-plane config dataclasses.

Split out of the monolithic training/config.py. These are pure, self-contained value objects
(they reference only each other), consumed by DataConfig / TrainConfig and the async runtime.
"""

import dataclasses
from typing import Any, Literal


@dataclasses.dataclass(frozen=True)
class RepoSpec:
    """LeRobot repo plus an optional explicit episode subset for dataset views."""

    repo_id: str
    episode_ids: tuple[int, ...] | None = None
    missing_feature_defaults: dict[str, Any] = dataclasses.field(default_factory=dict)
    # Immutable preprocessing labels, relative to the repo root; pins a published p70 revision.
    advantage_snapshot: str | None = None


@dataclasses.dataclass(frozen=True)
class EpisodeReplayConfig:
    """Episode-aware traversal for one weighted sampler group.

    ``newest_first_round_robin`` traverses every frame once per pass. The initial pass starts newest-first; later
    arrivals alternate with the existing FIFO backlog, while frames within each episode are deterministically
    shuffled for every pass.
    """

    mode: Literal["newest_first_round_robin"] = "newest_first_round_robin"
    frames_per_turn: int = 1
    shuffle_frames: bool = True


@dataclasses.dataclass(frozen=True)
class SamplerGroupConfig:
    """One weighted sampler group selected by simple column predicates."""

    name: str
    weight: float
    where: dict[str, Any] = dataclasses.field(default_factory=dict)
    episode_replay: EpisodeReplayConfig | None = None


@dataclasses.dataclass(frozen=True)
class SamplerConfig:
    """Config-driven training sampler.

    Supported type values:
    - "weighted_column_groups": samples each batch from configured column groups.
    - "column_balanced": balances batches across values from one metadata column.
    - "recent_policy": emphasizes samples generated by recent policy_id values.
    """

    type: str = "weighted_column_groups"
    groups: tuple[SamplerGroupConfig, ...] = ()
    replacement: bool = True
    drop_empty_groups: bool = False
    current_policy_id: int | None = None
    where: dict[str, Any] = dataclasses.field(default_factory=dict)
    column: str | None = None
    values: tuple[Any, ...] | None = None
    policy_id_column: str = "policy_id"
    recent_policy_window: int = 1
    include_current_policy: bool = True
    current_policy_weight: float = 1.0
    recent_policy_weight: float = 1.0
    older_policy_weight: float = 0.0


@dataclasses.dataclass(frozen=True)
class DatasetViewConfig:
    """Runtime dataset view watcher settings for async training."""

    latest_path: str | None = None
    poll_interval_steps: int = 100
    reload_on_change: bool = True


@dataclasses.dataclass(frozen=True)
class CheckpointMergeConfig:
    """Merges independently trained action and value checkpoints."""

    role: Literal["action", "value"]
    output_dir: str


@dataclasses.dataclass(frozen=True)
class CheckpointPublisherConfig:
    """Publishes saved checkpoints through a small local/cloud registry."""

    output_dir: str | None = None
    policy_id: int | None = None
    increment_policy_id: bool = False
    copy_checkpoint: bool = True
    reload_after_publish: bool = False
    async_publish: bool = True
    merge: CheckpointMergeConfig | None = None


@dataclasses.dataclass(frozen=True)
class CheckpointSwitchConfig:
    """In-process checkpoint rebase settings for long-running async training."""

    latest_path: str | None = None
    poll_interval_steps: int = 100
    reset_optimizer: bool = True
    reset_ema: bool = True
    preserve_global_step: bool = True


@dataclasses.dataclass(frozen=True)
class AsyncTrainStreamConfig:
    """One async training data stream with its own dataset view and train types."""

    name: str
    train_type: tuple[str, ...]
    train_type_by_target_policy_id: dict[int, tuple[str, ...]] = dataclasses.field(default_factory=dict)
    data: Any | None = None
    dataset_view: DatasetViewConfig = dataclasses.field(default_factory=DatasetViewConfig)
    steps_per_cycle: int = 1


@dataclasses.dataclass(frozen=True)
class GpuUtilizationMonitorConfig:
    enabled: bool = False
    sample_interval_s: float = 5.0
    target_percent: float = 90.0
    warn_below_target: bool = True
    warmup_steps: int = 0


@dataclasses.dataclass(frozen=True)
class AsyncTrainingConfig:
    dataset_view: DatasetViewConfig = dataclasses.field(default_factory=DatasetViewConfig)
    checkpoint_publisher: CheckpointPublisherConfig = dataclasses.field(default_factory=CheckpointPublisherConfig)
    checkpoint_switch: CheckpointSwitchConfig = dataclasses.field(default_factory=CheckpointSwitchConfig)
    disable_persistent_workers_on_reload: bool = True
    save_final_checkpoint: bool = True
    publish_on_save_interval: bool = False
    # Split action/value merge mode publishes exactly one checkpoint at the end of each policy round. The
    # checkpoint is still indexed by (policy_id, train_step), but this field owns the round boundary instead
    # of the generic view-update save window below.
    split_round_steps: int | None = None
    save_steps_after_view_update: int | None = None
    max_publish_steps_after_view_update: int | None = None
    compute_burst_steps: int = 1
    streams: tuple[AsyncTrainStreamConfig, ...] = ()
    gpu_monitor: GpuUtilizationMonitorConfig = dataclasses.field(default_factory=GpuUtilizationMonitorConfig)
    # Dual-source incremental dataloader: keep immutable repos in the multiprocess "stable" loader while the
    # growing current-policy repo lives in a main-thread live source that appends episodes in place. Within a
    # policy generation, new episodes grow the live source (no ~73s rebuild); cross-generation still rebuilds.
    # Trades ~1.4x steady-state throughput for near-zero-latency ingestion — only enable for live runs where
    # episodes arrive frequently. See docs/async_reload_latency_optimization.md §11-12. Default off.
    dual_source_loader: bool = False
